-- 5. Create investments table
CREATE TABLE IF NOT EXISTS investments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    date TEXT,
    description TEXT,
    amount DOUBLE PRECISION NOT NULL,
    account_id BIGINT REFERENCES investment_accounts(id),
    account_name TEXT,
    type TEXT NOT NULL CHECK (type IN ('deposit', 'withdrawal'))
);

ALTER TABLE investments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "select for auth" ON investments FOR SELECT TO authenticated USING (true);
CREATE POLICY "insert for auth" ON investments FOR INSERT TO authenticated WITH CHECK (true);
GRANT ALL ON TABLE investments TO anon, authenticated, service_role;
GRANT ALL ON SEQUENCE investments_id_seq TO anon, authenticated, service_role;

