-- 8. Create views
CREATE OR REPLACE VIEW investment_account_summary AS
SELECT 
    id,
    name,
    type,
    currency,
    balance as real_balance,
    capital as total_capital,
    starting_capital,
    balance - capital as pnl,
    CASE WHEN capital > 0 THEN ((balance - capital) / capital) * 100 ELSE 0 END as pnl_percent
FROM investment_accounts;

GRANT ALL ON investment_account_summary TO anon, authenticated, service_role;

CREATE OR REPLACE VIEW monthly_income_summary AS
SELECT 
    EXTRACT(YEAR FROM created_at)::INTEGER as year,
    EXTRACT(MONTH FROM created_at)::INTEGER as month,
    SUM(amount) as total_income
FROM incomes
GROUP BY EXTRACT(YEAR FROM created_at), EXTRACT(MONTH FROM created_at)
ORDER BY year, month;

GRANT ALL ON monthly_income_summary TO anon, authenticated, service_role;

CREATE OR REPLACE VIEW monthly_investment_summary AS
SELECT 
    EXTRACT(YEAR FROM created_at)::INTEGER as year,
    EXTRACT(MONTH FROM created_at)::INTEGER as month,
    account_id,
    account_name,
    SUM(CASE WHEN type = 'deposit' THEN amount ELSE 0 END) as deposits,
    SUM(CASE WHEN type = 'withdrawal' THEN amount ELSE 0 END) as withdrawals,
    SUM(CASE WHEN type = 'deposit' THEN amount ELSE -amount END) as net
FROM investments
GROUP BY EXTRACT(YEAR FROM created_at), EXTRACT(MONTH FROM created_at), account_id, account_name
ORDER BY year, month;

GRANT ALL ON monthly_investment_summary TO anon, authenticated, service_role;

